      decoderUnique[norm] = word.trim();
    }
  }

  final finalDecoder = decoderUnique.values.toList()..sort();
  File(decoderPath).writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(finalDecoder)}\n',
  );
  print('decoder: wrote ${finalDecoder.length} unique words.');
}
