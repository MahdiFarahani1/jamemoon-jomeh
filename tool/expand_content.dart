import 'dart:convert';
import 'dart:io';

String normalize(String value) => value
    .trim()
    .replaceAll('ي', 'ی')
    .replaceAll('ك', 'ک')
    .replaceAll(RegExp(r'[\u064B-\u065F\u0670]'), '')
    .replaceAll(RegExp(r'[\s\u200c]+'), ' ');

String normalizeDecoderWord(String input) => input
    .trim()
    .toLowerCase()
    .replaceAll('ي', 'ی')
    .replaceAll('ى', 'ی')
    .replaceAll('ك', 'ک')
    .replaceAll(RegExp(r'[\u064B-\u065F\u0670\u0640]'), '')
    .replaceAll(RegExp(r'[\s\u200c\u200d]+'), '');

bool isDecoderWord(String input) =>
    RegExp(r'^[a-z\u0621-\u063a\u0641-\u064a\u0671-\u06d3]+$')
        .hasMatch(normalizeDecoderWord(input)) &&
    !RegExp(r'\s').hasMatch(input);

void writePack(String path, List<Map<String, Object>> rows) {
  File(path).writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(rows)}\n',
  );
}

void splitPack(String folder, List<Map<String, Object>> rows, String primaryKey) {
  if (rows.length != 800) {
    throw StateError('$folder expected 800 rows, got ${rows.length}');
  }
  final seen = <String>{};
  for (final row in rows) {
    final raw = row[primaryKey] as String;
    final norm = normalize(raw);
    if (!seen.add(norm)) {
      throw StateError('$folder duplicate normalized item: "$raw" ($norm)');
    }
    if (folder == 'taboo') {
      final forbidden = row['forbiddenWords'] as List;
      if (forbidden.length != 5 || forbidden.any((w) => (w as String).trim().isEmpty)) {
        throw StateError('$folder card "${row['id']}" has invalid forbidden words');
      }
    }
  }

  final free = rows.take(400).toList();
  final full = rows.skip(400).toList();

  writePack('assets/data/$folder/pack_free.json', free);
  writePack('assets/data/$folder/pack_full.json', full);
  print('$folder: wrote 400 free + 400 full cards (total 800).');
}

